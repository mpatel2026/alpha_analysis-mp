def die(msg):
    sys.exit("error: " + msg)


def deep_update(base, extra):
    for k, v in extra.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            deep_update(base[k], v)
        else:
            base[k] = v
    return base


def fill(value, ctx):
    """Format {key} placeholders in a string from ctx (two passes so templated
    fields may reference other templated fields, e.g. marker_file -> sim_name)."""
    if not isinstance(value, str):
        return value
    for _ in range(2):
        try:
            value = value.format(**ctx)
        except KeyError as e:
            die("unknown placeholder {%s} in %r" % (e.args[0], value))
    return value


def dirslash(path):
    return path if path.endswith("/") else path + "/"


def abspath(path):
    return path if os.path.isabs(path) else os.path.join(REPO_DIR, path)


def load_manifest(path):
    with open(path) as f:
        m = json.load(f)
    recipe_name = m.get("recipe")
    if recipe_name not in RECIPES:
        die("manifest 'recipe' must be one of %s" % sorted(RECIPES))
    recipe = copy.deepcopy(RECIPES[recipe_name])
    if "prep_steps" in m:
        recipe["prep_steps"] = m["prep_steps"]
    deep_update(recipe["slurm"], m.get("slurm", {}))
    site = dict(SITE, **m.get("site", {}))
    name = os.path.splitext(os.path.basename(path))[0]
    camp_dir = os.path.join(os.path.dirname(os.path.abspath(path)), name)
    return m, recipe, site, name, camp_dir


def case_entries(m):
    """Yield (tag, overrides) from the manifest's "cases" list and/or "tag_glob".

    tag_glob is a shell pattern for {tag}; tags are discovered by globbing the
    defaults' inp_dir + equil_file template with {tag} replaced by the pattern."""
    defaults = m.get("defaults", {})
    if "tag_glob" in m:
        template = dirslash(defaults.get("inp_dir", "")) + defaults.get("equil_file", "")
        if template.count("{tag}") != 1:
            die("tag_glob needs defaults.equil_file to contain {tag} exactly once")
        prefix, suffix = template.split("{tag}")
        for p in sorted(glob.glob(prefix + m["tag_glob"] + suffix)):
            yield p[len(prefix):len(p) - len(suffix)], {}
    for entry in m.get("cases", []):
        if isinstance(entry, str):
            yield entry, {}
        else:
            yield entry.get("tag", ""), entry


def expand_cases(m, recipe):
    cases = []
    for tag, overrides in case_entries(m):
        raw = dict(recipe.get("params", {}), **m.get("defaults", {}))
        raw.update(overrides)
        raw["tag"] = tag
        case = {k: fill(v, raw) for k, v in raw.items()}
        for key in ("inp_dir", "out_dir", "equil_file", "sim_name"):
            if not case.get(key):
                die("case %r is missing %r" % (tag, key))
        case["inp_dir"] = dirslash(case["inp_dir"])
        case["out_dir"] = dirslash(case["out_dir"])
        if case.get("marker_file"):
            case["marker_file"] = abspath(case["marker_file"])
        case["_h5"] = case["out_dir"] + case["sim_name"] + ".h5"
        case["_required"] = [fill(r, case) for r in recipe["required"]
                             if all(k in case for k in re.findall(r"{(\w+)}", r))]
        missing_keys = [k for r in recipe["required"] for k in re.findall(r"{(\w+)}", r)
                        if k not in case]
        case["_errors"] = ["missing key %r" % k for k in sorted(set(missing_keys))]
        cases.append(case)
    if not cases:
        die("manifest has no cases")
    names = [c["sim_name"] for c in cases]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        die("duplicate sim_name(s): %s" % ", ".join(dupes))
    return cases


def validate(cases):
    for c in cases:
        c["_errors"] += ["not found: " + p for p in c["_required"] if not os.path.exists(p)]
        if not os.path.isdir(c["out_dir"]):
            c["_errors"].append("out_dir does not exist: " + c["out_dir"])


def sbatch_directives(res, site):
    lines = ["#SBATCH --account=%s" % site["account"], "#SBATCH --constraint=gpu"]
    for k, v in res.items():
        if k != "max_concurrent":
            lines.append("#SBATCH --%s=%s" % (k, v))
    if site.get("mail_user"):
        lines.append("#SBATCH --mail-type=%s" % site["mail_type"])
        lines.append("#SBATCH --mail-user=%s" % site["mail_user"])
    return "\n".join(lines)


def write_plan(manifest_path, m, recipe, site, name, camp_dir, cases):
    for sub in ("params", "logs", "post", "figures"):
        os.makedirs(os.path.join(camp_dir, sub), exist_ok=True)
    rows = []
    for c in cases:
        params = {k: v for k, v in c.items() if not k.startswith("_")}
        ppath = os.path.join(camp_dir, "params", c["sim_name"] + ".json")
        with open(ppath, "w") as f:
            json.dump(params, f, indent=2)
            f.write("\n")
        rows.append("\t".join([c["sim_name"], c["_h5"], ppath, c.get("marker_file") or "-"]))
    with open(os.path.join(camp_dir, "cases.tsv"), "w") as f:
        f.write("\n".join(rows) + "\n")

    fmt = dict(name=name, camp_dir=camp_dir, repo_dir=REPO_DIR,
               manifest=os.path.relpath(os.path.abspath(manifest_path), REPO_DIR), **site)
    fmt["steps"] = "\n".join("$SRUN " + s for s in recipe["prep_steps"])
    for stage, bodies in STAGE_BODIES.items():
        if stage not in recipe["slurm"]:
            continue
        text = "".join([HEADER] + bodies).format(
            stage=stage, directives=sbatch_directives(recipe["slurm"][stage], site), **fmt)
        with open(os.path.join(camp_dir, stage + ".sbatch"), "w") as f:
            f.write(text)


def parse_indices(spec, n):
    if not spec:
        return list(range(1, n + 1))
    out = set()
    for part in spec.split(","):
        a, _, b = part.partition("-")
        out.update(range(int(a), int(b or a) + 1))
    bad = [i for i in out if not 1 <= i <= n]
    if bad:
        die("case indices out of range 1-%d: %s" % (n, bad))
    return sorted(out)


def array_spec(indices):
    parts, start = [], None
    for i, x in enumerate(indices):
        if start is None:
            start = x
        if i + 1 == len(indices) or indices[i + 1] != x + 1:
            parts.append(str(start) if start == x else "%d-%d" % (start, x))
            start = None
    return ",".join(parts)


def run_cmd(cmd):
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                       universal_newlines=True)
    if p.returncode != 0:
        die("%s failed:\n%s" % (" ".join(cmd), p.stderr.strip()))
    return p.stdout.strip()


def print_table(cases, indices=None, extra=None):
    w = max(len(c["sim_name"]) for c in cases)
    for i, c in enumerate(cases, 1):
        if indices and i not in indices:
            continue
        h5 = "h5 exists" if os.path.exists(c["_h5"]) else "no h5"
        info = extra(i, c) if extra else h5
        print("  %3d  %-*s  %s" % (i, w, c["sim_name"], info))
        for e in c["_errors"]:
            print("        ! " + e)


def cmd_plan(args, quiet=False):
    m, recipe, site, name, camp_dir = load_manifest(args.manifest)
    cases = expand_cases(m, recipe)
    validate(cases)
    write_plan(args.manifest, m, recipe, site, name, camp_dir, cases)
    if not quiet:
        print("campaign %s  (recipe: %s, %d cases)" % (name, m["recipe"], len(cases)))
        print_table(cases)
        print("wrote %s/{params/, cases.tsv, *.sbatch}" %
              os.path.relpath(camp_dir))
        n_err = sum(bool(c["_errors"]) for c in cases)
        if n_err:
            print("%d case(s) have errors -- fix before submitting" % n_err)
    return m, recipe, name, camp_dir, cases


def cmd_submit(args):
    m, recipe, name, camp_dir, cases = cmd_plan(args, quiet=True)
    stages = args.stages.split(",")
    if not set(stages) <= {"prep", "run", "post"}:
        die("--stages must be a comma list of prep, run, post")
    available = set(recipe["slurm"]) | ({"prep", "run"} if "prep_run" in recipe["slurm"] else set())
    stages = [s for s in stages if s in available]
    if not stages:
        die("recipe %r has none of the requested stages (has: %s)"
            % (m["recipe"], ", ".join(sorted(available))))
    indices = parse_indices(args.cases, len(cases))
    sel = [cases[i - 1] for i in indices]

    problems = [c for c in sel if c["_errors"]]
    if "prep" not in stages:  # run/post only: inputs must already exist
        problems = [c for c in sel if not os.path.exists(c["_h5"])]
        if "post" in stages:
            problems += [c for c in sel if c not in problems
                         and not os.path.exists(c["inp_dir"] + c["equil_file"])]
    if problems:
        print_table(cases, {cases.index(c) + 1 for c in problems})
        die("%d selected case(s) not ready (see above)" % len(problems))
    if "prep" in stages:
        existing = [i for i in indices if os.path.exists(cases[i - 1]["_h5"])]
        if existing:
            print("note: prep will delete and recreate these existing h5 files:")
            print_table(cases, set(existing))

    spec = array_spec(indices)
    jobs = [s for s in ("prep", "run", "post") if s in stages]
    covers = {s: [s] for s in jobs}
    if recipe.get("combine") and jobs[:2] == ["prep", "run"]:
        jobs = ["prep_run"]  # includes post
        covers = {"prep_run": ["prep", "run", "post"]}
    print("campaign %s: submitting %s for cases %s" % (name, " -> ".join(jobs), spec))
    prev = None
    for stage in jobs:
        throttle = recipe["slurm"][stage].get("max_concurrent")
        cmd = ["sbatch", "--parsable", "--array=" + spec + ("%%%d" % throttle if throttle else "")]
        if prev:
            cmd += ["--dependency=aftercorr:" + prev, "--kill-on-invalid-dep=yes"]
        if args.dry_run:
            cmd.insert(1, "--test-only")
        cmd.append(os.path.join(camp_dir, stage + ".sbatch"))
        print("  $ " + " ".join(cmd))
        if args.dry_run:
            p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                               universal_newlines=True)
            print("    " + p.stdout.strip().replace("\n", "\n    "))
            prev = "1"  # placeholder so the run stage shows its dependency flags
            continue
        jobid = run_cmd(cmd).split(";")[0]
        print("    -> job %s" % jobid)
        with open(os.path.join(camp_dir, "jobs.jsonl"), "a") as f:
            f.write(json.dumps({"time": datetime.datetime.now().isoformat(timespec="seconds"),
                                "stage": stage, "covers": covers[stage], "jobid": jobid,
                                "cases": indices}) + "\n")
        prev = jobid


def sacct_states(jobids):
    if not jobids:
        return {}
    p = subprocess.run(["sacct", "-nP", "-X", "-j", ",".join(jobids),
                        "--format=JobID,State"],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
    states = {}
    for line in p.stdout.splitlines():
        jid, _, state = line.partition("|")
        base, _, task = jid.partition("_")
        state = state.split()[0] if state else "?"
        if task.startswith("["):  # pending array chunk, e.g. 123_[4-7%2]
            for i in parse_indices(task.strip("[]").split("%")[0], 10 ** 6):
                states[(base, i)] = state
        elif task.isdigit():
            states[(base, int(task))] = state
    # sacct lists only one record for a pending array; squeue -r has every task
    p = subprocess.run(["squeue", "-h", "-r", "-j", ",".join(jobids), "-o", "%i|%T"],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
    for line in p.stdout.splitlines():
        jid, _, state = line.strip().partition("|")
        base, _, task = jid.partition("_")
        if task.isdigit():
            states[(base, int(task))] = state
    return states


def cmd_status(args):
    m, recipe, name, camp_dir, cases = cmd_plan(args, quiet=True)
    latest = {}  # (stage, case index) -> jobid of most recent submission
    jobs_path = os.path.join(camp_dir, "jobs.jsonl")
    if os.path.exists(jobs_path):
        with open(jobs_path) as f:
            for line in f:
                rec = json.loads(line)
                for stage in rec.get("covers", rec["stage"].split("_")):
                    for i in rec["cases"]:
                        latest[(stage, i)] = rec["jobid"]
    states = sacct_states(sorted(set(latest.values())))

    def info(i, c):
        h5 = c["_h5"]
        out = ["%5.0f MB" % (os.path.getsize(h5) / 1e6) if os.path.exists(h5) else "   no h5"]
        for stage in ("prep", "run", "post"):
            jid = latest.get((stage, i))
            out.append("%s %-10s" % (stage, states.get((jid, i), "?") if jid else "-"))
        return "  ".join(out)

    print("campaign %s  (recipe: %s, %d cases)" % (name, m["recipe"], len(cases)))
    print_table(cases, extra=info)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd")
    for cmd in ("plan", "submit", "status"):
        p = sub.add_parser(cmd)
        p.add_argument("manifest", help="campaign manifest JSON (campaigns/<name>.json)")
        if cmd == "submit":
            p.add_argument("--stages", default="prep,run,post",
                           help="comma list of prep, run, post (default: all three)")
            p.add_argument("--cases", help="1-based case indices, e.g. 1-3,7 (default all)")
            p.add_argument("--dry-run", action="store_true",
                           help="validate with sbatch --test-only, submit nothing")
    args = ap.parse_args()
    if not args.cmd:
        ap.print_help()
        sys.exit(1)
    {"plan": cmd_plan, "submit": cmd_submit, "status": cmd_status}[args.cmd](args)


if __name__ == "__main__":
    main()
